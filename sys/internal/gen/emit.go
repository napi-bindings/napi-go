package main

import (
	"fmt"
	"go/format"
	"sort"
	"strings"
)

const generatedHeader = "Code generated by sys/internal/gen from node-api-headers " + headersVersion + ". DO NOT EDIT."

// statusUnavailable è lo status restituito dai wrapper quando il processo host non esporta la
// funzione. Non collide con i valori di napi_status (oggi 0–23).
const statusUnavailable = 1000

// API è il risultato completo del parsing, pronto per l'emissione.
type API struct {
	Funcs      []FuncBinding
	Enums      []Enum
	MaxVersion int
}

// File generato: percorso relativo alla directory di sys e contenuto.
type File struct {
	Path    string
	Content []byte
}

func emitAll(api API) ([]File, error) {
	goAPI, err := gofmt("zz_api.go", emitGoAPI(api))
	if err != nil {
		return nil, err
	}
	goEnums, err := gofmt("zz_enums.go", emitGoEnums(api))
	if err != nil {
		return nil, err
	}
	nc, err := gofmt("zz_nocallback.go", emitNoCallback(api, false))
	if err != nil {
		return nil, err
	}
	ncx, err := gofmt("zz_nocallback_experimental.go", emitNoCallback(api, true))
	if err != nil {
		return nil, err
	}
	check, err := gofmt("zz_enums_check.go", emitEnumCheck(api))
	if err != nil {
		return nil, err
	}
	return []File{
		{"zz_api.h", []byte(emitCHeader(api))},
		{"zz_api.c", []byte(emitCSource(api))},
		{"zz_api.go", goAPI},
		{"zz_enums.go", goEnums},
		{"zz_nocallback.go", nc},
		{"zz_nocallback_experimental.go", ncx},
		{"zz_enums_check.go", check},
	}, nil
}

func gofmt(name, src string) ([]byte, error) {
	out, err := format.Source([]byte(src))
	if err != nil {
		return nil, fmt.Errorf("%s: gofmt: %w\n%s", name, err, src)
	}
	return out, nil
}

func cParamList(f FuncBinding, withNames bool) string {
	var parts []string
	for _, p := range f.Func.Params {
		if withNames {
			parts = append(parts, p.CType+" "+p.Name)
		} else {
			parts = append(parts, p.CType)
		}
	}
	if len(parts) == 0 {
		return "void"
	}
	return strings.Join(parts, ", ")
}

func emitCHeader(api API) string {
	var b strings.Builder
	w := func(format string, a ...any) { fmt.Fprintf(&b, format, a...) }
	w("/* %s */\n\n", generatedHeader)
	w("/*\n * Tabella delle funzioni Node-API risolte a runtime e wrapper C usati da zz_api.go.\n")
	w(" * Solo dichiarazioni e funzioni static inline: l'header finisce anche in _cgo_export.h.\n */\n")
	w("#ifndef NAPI_GO_ZZ_API_H\n#define NAPI_GO_ZZ_API_H\n\n")
	w("#include <stddef.h>\n#include <stdint.h>\n#include <stdlib.h> /* abort */\n#include <node_api.h>\n\n")
	w("#define GN_STATUS_UNAVAILABLE ((napi_status)%d)\n\n", statusUnavailable)
	w("enum {\n")
	for i, f := range api.Funcs {
		w("  GN_FN_%s = %d,\n", f.Name, i)
	}
	w("  GN_API_COUNT = %d\n};\n\n", len(api.Funcs))
	w("typedef struct {\n  const char* name;\n  int version; /* versione Node-API minima */\n} gn_api_entry;\n\n")
	w("/* Puntatori risolti da gn_api_load (loader.c); NULL se il processo host non li esporta. */\n")
	w("extern void* gn_api[GN_API_COUNT];\n")
	w("extern const gn_api_entry gn_api_entries[GN_API_COUNT];\n\n")

	for _, f := range api.Funcs {
		w("/* %s — Node-API %d */\n", f.Name, f.Version)
		w("typedef %s(NAPI_CDECL* gn_fp_%s)(%s);\n", f.Ret, f.Name, cParamList(f, true))

		var helperParams, callArgs []string
		outIndex := map[string]int{}
		for i, o := range f.Outs {
			outIndex[o.Name] = i
		}
		for _, p := range f.Params {
			if p.Role == roleOut {
				k := outIndex[p.Name]
				callArgs = append(callArgs, fmt.Sprintf("(gn_want & %du) ? &gn_r.o%d : NULL", 1<<k, k))
				continue
			}
			helperParams = append(helperParams, p.CParam)
			callArgs = append(callArgs, p.CArg)
		}
		if len(f.Outs) > 0 {
			helperParams = append(helperParams, "unsigned int gn_want")
		}
		hp := strings.Join(helperParams, ", ")
		if hp == "" {
			hp = "void"
		}
		call := fmt.Sprintf("gn_f(%s)", strings.Join(callArgs, ", "))
		fp := fmt.Sprintf("gn_fp_%s gn_f = (gn_fp_%s)gn_api[GN_FN_%s];", f.Name, f.Name, f.Name)

		switch {
		case f.Ret == "void":
			w("static inline void gn_%s(%s) {\n  %s\n", f.Name, hp, fp)
			w("  if (gn_f == NULL) abort(); /* impossibile segnalare l'errore: termina comunque */\n")
			w("  %s;\n}\n\n", call)
		case len(f.Outs) == 0:
			w("static inline napi_status gn_%s(%s) {\n  %s\n", f.Name, hp, fp)
			w("  if (gn_f == NULL) return GN_STATUS_UNAVAILABLE;\n  return %s;\n}\n\n", call)
		default:
			w("typedef struct {\n  napi_status status;\n")
			for i, o := range f.Outs {
				w("  %s o%d;\n", o.OutType, i)
			}
			w("} gn_r_%s;\n", f.Name)
			w("static inline gn_r_%s gn_%s(%s) {\n", f.Name, f.Name, hp)
			w("  gn_r_%s gn_r = {GN_STATUS_UNAVAILABLE};\n  %s\n", f.Name, fp)
			w("  if (gn_f == NULL) return gn_r;\n  gn_r.status = %s;\n  return gn_r;\n}\n\n", call)
		}
	}
	w("#endif /* NAPI_GO_ZZ_API_H */\n")
	return b.String()
}

func emitCSource(api API) string {
	var b strings.Builder
	fmt.Fprintf(&b, "/* %s */\n\n#include \"zz_api.h\"\n\n", generatedHeader)
	b.WriteString("void* gn_api[GN_API_COUNT];\n\n")
	b.WriteString("const gn_api_entry gn_api_entries[GN_API_COUNT] = {\n")
	for _, f := range api.Funcs {
		fmt.Fprintf(&b, "  {%q, %d},\n", f.Name, f.Version)
	}
	b.WriteString("};\n")
	return b.String()
}

func hasPointerParam(f FuncBinding) bool {
	for _, p := range f.Params {
		if p.Role == rolePtr {
			return true
		}
	}
	return false
}

func emitGoAPI(api API) string {
	var b strings.Builder
	w := func(format string, a ...any) { fmt.Fprintf(&b, format, a...) }
	w("// %s\n\npackage sys\n\n", generatedHeader)
	w("/*\n")
	for _, f := range api.Funcs {
		if f.NoEscape && hasPointerParam(f) {
			w("#cgo noescape gn_%s\n", f.Name)
		}
	}
	w("#include \"zz_api.h\"\n*/\nimport \"C\"\n\nimport \"unsafe\"\n\n")

	w("// Fn identifica una funzione Node-API della tabella risolta a runtime.\ntype Fn int\n\n")
	w("// Funzioni Node-API, nell'ordine degli header.\nconst (\n")
	for i, f := range api.Funcs {
		if i == 0 {
			w("\tFn%s Fn = iota // %s\n", f.GoName, f.Name)
		} else {
			w("\tFn%s // %s\n", f.GoName, f.Name)
		}
	}
	w(")\n\n")
	w("// fnCount è il numero di funzioni nella tabella.\nconst fnCount = %d\n\n", len(api.Funcs))
	w("// MaxVersion è la versione Node-API più alta descritta dagli header vendorizzati.\n")
	w("const MaxVersion = %d\n\n", api.MaxVersion)
	w("// La tabella Go e quella C devono avere la stessa lunghezza.\n")
	w("var (\n\t_ [fnCount - C.GN_API_COUNT]struct{}\n\t_ [C.GN_API_COUNT - fnCount]struct{}\n)\n\n")
	w("var fnInfo = [fnCount]struct {\n\tname    string\n\tversion uint8\n}{\n")
	for _, f := range api.Funcs {
		w("\t{%q, %d},\n", f.Name, f.Version)
	}
	w("}\n\n")

	for _, f := range api.Funcs {
		emitGoWrapper(&b, f)
	}
	return b.String()
}

func emitGoWrapper(b *strings.Builder, f FuncBinding) {
	w := func(format string, a ...any) { fmt.Fprintf(b, format, a...) }
	w("// %s chiama %s (Node-API %d).\n", f.GoName, f.Name, f.Version)
	if len(f.Outs) > 0 {
		w("// Le uscite vengono scritte solo se lo status è StatusOK; un puntatore nil diventa NULL.\n")
	}
	if !f.NoEscape {
		w("// I buffer passati vengono conservati da Node-API: non devono essere memoria Go.\n")
	}
	w("//\n// https://nodejs.org/api/n-api.html#%s\n", f.Name)

	var params, args []string
	for _, p := range f.Params {
		params = append(params, p.GoName+" "+p.GoType)
		if p.Role != roleOut {
			args = append(args, p.ToC)
		}
	}
	ret := " Status"
	if f.Ret == "void" {
		ret = ""
	}
	w("func %s(%s)%s {\n", f.GoName, strings.Join(params, ", "), ret)

	switch {
	case f.Ret == "void":
		w("\tC.gn_%s(%s)\n}\n\n", f.Name, strings.Join(args, ", "))
	case len(f.Outs) == 0:
		w("\treturn Status(C.gn_%s(%s))\n}\n\n", f.Name, strings.Join(args, ", "))
	default:
		w("\tvar gnWant C.uint\n")
		for i, o := range f.Outs {
			w("\tif %s != nil {\n\t\tgnWant |= %d\n\t}\n", o.GoName, 1<<i)
		}
		args = append(args, "gnWant")
		w("\tgnR := C.gn_%s(%s)\n", f.Name, strings.Join(args, ", "))
		w("\tif gnR.status == C.napi_ok {\n")
		for i, o := range f.Outs {
			w("\t\tif %s != nil {\n\t\t\t*%s = %s\n\t\t}\n", o.GoName, o.GoName, fmt.Sprintf(o.FromC, fmt.Sprintf("gnR.o%d", i)))
		}
		w("\t}\n\treturn Status(gnR.status)\n}\n\n")
	}
}

func emitGoEnums(api API) string {
	var b strings.Builder
	w := func(format string, a ...any) { fmt.Fprintf(&b, format, a...) }
	w("// %s\n\npackage sys\n\n", generatedHeader)
	enums := append([]Enum(nil), api.Enums...)
	sort.Slice(enums, func(i, j int) bool { return enumConfig[enums[i].CName].goType < enumConfig[enums[j].CName].goType })
	for _, e := range enums {
		n := enumConfig[e.CName]
		w("// %s corrisponde a %s.\ntype %s int32\n\n", n.goType, e.CName, n.goType)
		w("// Valori di %s.\nconst (\n", e.CName)
		for _, m := range e.Members {
			w("\t%s %s = %d // %s\n", goEnumName(m.CName, n), n.goType, m.Value, m.CName)
		}
		if e.CName == "napi_status" {
			w("\n\t// StatusUnavailable: il processo host non esporta la funzione chiamata (versione\n")
			w("\t// di Node.js troppo vecchia). Non è un valore di napi_status.\n")
			w("\tStatusUnavailable Status = %d\n", statusUnavailable)
		}
		w(")\n\n")
	}
	for _, e := range enums {
		if e.CName != "napi_status" && e.CName != "napi_valuetype" {
			continue
		}
		n := enumConfig[e.CName]
		recv := strings.ToLower(n.goType[:1])
		w("// String restituisce il nome C del valore.\nfunc (%s %s) String() string {\n\tswitch %s {\n", recv, n.goType, recv)
		for _, m := range e.Members {
			w("\tcase %s:\n\t\treturn %q\n", goEnumName(m.CName, n), m.CName)
		}
		if e.CName == "napi_status" {
			w("\tcase StatusUnavailable:\n\t\treturn \"napi-go: function unavailable in this Node.js\"\n")
		}
		w("\t}\n\treturn \"%s(\" + itoa(int64(%s)) + \")\"\n}\n\n", e.CName, recv)
	}
	return b.String()
}

func emitNoCallback(api API, experimental bool) string {
	var b strings.Builder
	w := func(format string, a ...any) { fmt.Fprintf(&b, format, a...) }
	w("// %s\n\n", generatedHeader)
	if experimental {
		w("//go:build napi_go_experimental\n\n")
	} else {
		w("//go:build !napi_go_experimental\n\n")
	}
	w("package sys\n\n")
	if experimental {
		w("// Con napi_go_experimental i finalizer possono essere eseguiti durante il GC di V8, cioè\n")
		w("// dentro qualunque funzione che alloca: nocallback solo per le funzioni che non allocano.\n")
	} else {
		w("// Funzioni Node-API che non rientrano mai in Go durante la chiamata (vedi policy.go del\n")
		w("// generatore). Con noescape permettono a cgo di lasciare sullo stack i buffer passati.\n")
	}
	w("\n/*\n")
	for _, f := range api.Funcs {
		if (experimental && f.NoAlloc) || (!experimental && f.NoCallback) {
			w("#cgo nocallback gn_%s\n", f.Name)
		}
	}
	w("#include \"zz_api.h\"\n*/\nimport \"C\"\n")
	return b.String()
}

// emitEnumCheck confronta a tempo di compilazione ogni costante Go con il valore calcolato dal
// compilatore C: una differenza dà un indice negativo o fuori intervallo.
func emitEnumCheck(api API) string {
	var b strings.Builder
	w := func(format string, a ...any) { fmt.Fprintf(&b, format, a...) }
	w("// %s\n\npackage sys\n\n", generatedHeader)
	w("// #include \"zz_api.h\"\nimport \"C\"\n\n")
	w("// I valori calcolati dal generatore devono coincidere con quelli del compilatore C.\nvar _ = [...]struct{}{\n")
	for _, e := range api.Enums {
		n := enumConfig[e.CName]
		for _, m := range e.Members {
			w("\t[1]struct{}{}[%s-C.%s],\n", goEnumName(m.CName, n), m.CName)
		}
	}
	w("}\n")
	return b.String()
}
