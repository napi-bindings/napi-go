// Command genwrappers writes napi/zz_wrappers.go: the generic wrappers of Layer 2 (Func0..Func8,
// Async0..Async8, Method0..Method8, Ctor0..Ctor8 and their variants), which differ only in arity
// and in the shape of the result. Run it with go generate ./napi; with -check it only verifies that
// the file is up to date (CI).
package main

import (
	"bytes"
	"fmt"
	"go/format"
	"log"
	"os"
	"strings"
)

// maxArity is the largest number of JS parameters of a wrapper; it matches GN_INLINE_ARGS, the
// arguments the C trampoline reads without a second Node-API call.
const maxArity = 8

// shape is one family of wrappers.
type shape struct {
	name    string // Func, FuncE, Proc, ...
	kind    string // funcDef kind
	recv    bool   // method: first parameter is *T
	ctx     bool   // async: first parameter is context.Context
	ctor    bool   // constructor
	result  bool   // returns a value R
	err     bool   // returns an error
	retType string // FuncDef, MethodDef[T], CtorDef[T]
	doc     string
}

var shapes = []shape{
	{name: "Func", kind: "kindFunc", result: true, retType: "FuncDef",
		doc: "wraps a function returning one value"},
	{name: "FuncE", kind: "kindFunc", result: true, err: true, retType: "FuncDef",
		doc: "wraps a function returning a value and an error; the error is thrown in JS"},
	{name: "Proc", kind: "kindFunc", retType: "FuncDef",
		doc: "wraps a function with no result (JS receives undefined)"},
	{name: "ProcE", kind: "kindFunc", err: true, retType: "FuncDef",
		doc: "wraps a function returning only an error; the error is thrown in JS"},
	{name: "Async", kind: "kindAsync", ctx: true, result: true, err: true, retType: "FuncDef",
		doc: "wraps a function run in a goroutine: JS receives a Promise resolved with its result or rejected with its error. Arguments are converted on the JS thread before the goroutine starts ([]byte are copied); ctx is canceled when the env is destroyed (Env.Async)"},
	{name: "AsyncProc", kind: "kindAsync", ctx: true, err: true, retType: "FuncDef",
		doc: "wraps a function run in a goroutine whose Promise resolves with undefined or rejects with its error (see Async1)"},
	{name: "Method", kind: "kindMethod", recv: true, result: true, retType: "MethodDef[T]",
		doc: "wraps a method of the class of T returning one value; the receiver is the Go value of this"},
	{name: "MethodE", kind: "kindMethod", recv: true, result: true, err: true, retType: "MethodDef[T]",
		doc: "wraps a method returning a value and an error"},
	{name: "MethodProc", kind: "kindMethod", recv: true, retType: "MethodDef[T]",
		doc: "wraps a method with no result"},
	{name: "MethodProcE", kind: "kindMethod", recv: true, err: true, retType: "MethodDef[T]",
		doc: "wraps a method returning only an error"},
	{name: "Ctor", kind: "kindCtor", ctor: true, retType: "CtorDef[T]",
		doc: "wraps the constructor of the class of T: it receives the converted arguments of new and returns the Go value of the instance (or an error, thrown in JS)"},
}

func main() {
	var b bytes.Buffer
	b.WriteString("// Code generated by napi/internal/genwrappers; DO NOT EDIT.\n\npackage napi\n\n")
	b.WriteString("import (\n\t\"context\"\n\t\"reflect\"\n\n\t\"github.com/napi-bindings/napi-go/sys\"\n)\n\n")
	b.WriteString("var _ context.Context // used by the Async wrappers\n\n")
	for _, s := range shapes {
		for n := 0; n <= maxArity; n++ {
			writeWrapper(&b, s, n)
		}
	}
	src, err := format.Source(b.Bytes())
	if err != nil {
		log.Fatalf("format: %v\n%s", err, b.Bytes())
	}
	const out = "zz_wrappers.go"
	if len(os.Args) > 1 && os.Args[1] == "-check" {
		cur, err := os.ReadFile(out)
		if err != nil {
			log.Fatal(err)
		}
		if !bytes.Equal(cur, src) {
			log.Fatalf("%s is out of date: run go generate ./napi", out)
		}
		return
	}
	if err := os.WriteFile(out, src, 0o644); err != nil {
		log.Fatal(err)
	}
}

func writeWrapper(b *bytes.Buffer, s shape, n int) {
	name := fmt.Sprintf("%s%d", s.name, n)
	// Type parameters.
	var tps []string
	if s.recv || s.ctor {
		tps = append(tps, "T")
	}
	for i := 1; i <= n; i++ {
		tps = append(tps, fmt.Sprintf("A%d", i))
	}
	if s.result {
		tps = append(tps, "R")
	}
	tpDecl := ""
	if len(tps) > 0 {
		tpDecl = "[" + strings.Join(tps, ", ") + " any]"
	}
	// Signature of the wrapped function.
	var in []string
	if s.ctx {
		in = append(in, "context.Context")
	}
	if s.recv {
		in = append(in, "*T")
	}
	for i := 1; i <= n; i++ {
		in = append(in, fmt.Sprintf("A%d", i))
	}
	var out []string
	switch {
	case s.ctor:
		out = []string{"*T", "error"}
	case s.result && s.err:
		out = []string{"R", "error"}
	case s.result:
		out = []string{"R"}
	case s.err:
		out = []string{"error"}
	}
	fnType := "func(" + strings.Join(in, ", ") + ")"
	switch len(out) {
	case 1:
		fnType += " " + out[0]
	case 2:
		fnType += " (" + strings.Join(out, ", ") + ")"
	}

	fmt.Fprintf(b, "// %s %s.\n", name, s.doc)
	fmt.Fprintf(b, "func %s%s(fn %s) %s {\n", name, tpDecl, fnType, s.retType)
	fmt.Fprintf(b, "\tif fn == nil {\n\t\tpanic(\"napi: %s(nil)\")\n\t}\n", name)
	var types []string
	for i := 1; i <= n; i++ {
		types = append(types, fmt.Sprintf("reflect.TypeFor[A%d]()", i))
	}
	typesExpr := "nil"
	if n > 0 {
		typesExpr = "[]reflect.Type{" + strings.Join(types, ", ") + "}"
	}
	resultExpr := "nil"
	if s.result {
		resultExpr = "reflect.TypeFor[R]()"
	}

	if s.ctor {
		fmt.Fprintf(b, "\td := newFuncDef(%q, %s, %s, nil, nil)\n", name, s.kind, typesExpr)
		fmt.Fprintf(b, "\treturn CtorDef[T]{d: d, make: func(cx call) (*T, error) {\n")
		writeArgs(b, n, "nil, err")
		fmt.Fprintf(b, "\t\treturn fn(%s)\n\t}}\n}\n\n", argList(n, ""))
		return
	}

	fmt.Fprintf(b, "\td := newFuncDef(%q, %s, %s, %s, nil)\n", name, s.kind, typesExpr, resultExpr)
	fmt.Fprintf(b, "\td.impl = func(cx call) (sys.Value, error) {\n")
	callArgs := argList(n, "")
	if s.recv {
		fmt.Fprintf(b, "\t\trecv, err := receiver[T](&cx)\n\t\tif err != nil {\n\t\t\treturn nil, err\n\t\t}\n")
		callArgs = argList(n, "recv")
	}
	writeArgs(b, n, "nil, err")
	if s.ctx {
		fmt.Fprintf(b, "\t\treturn startAsync(&cx, func(ctx context.Context) (Resolver, error) {\n")
		if s.result {
			fmt.Fprintf(b, "\t\t\tr, err := fn(%s)\n\t\t\tif err != nil {\n\t\t\t\treturn nil, err\n\t\t\t}\n", argList(n, "ctx"))
			fmt.Fprintf(b, "\t\t\treturn resolveWith(d, r), nil\n")
		} else {
			fmt.Fprintf(b, "\t\t\treturn nil, fn(%s)\n", argList(n, "ctx"))
		}
		fmt.Fprintf(b, "\t\t})\n\t}\n")
	} else {
		switch {
		case s.result && s.err:
			fmt.Fprintf(b, "\t\tr, err := fn(%s)\n\t\tif err != nil {\n\t\t\treturn nil, err\n\t\t}\n\t\treturn result(&cx, r)\n\t}\n", callArgs)
		case s.result:
			fmt.Fprintf(b, "\t\treturn result(&cx, fn(%s))\n\t}\n", callArgs)
		case s.err:
			fmt.Fprintf(b, "\t\treturn nil, fn(%s)\n\t}\n", callArgs)
		default:
			fmt.Fprintf(b, "\t\tfn(%s)\n\t\treturn nil, nil\n\t}\n", callArgs)
		}
	}
	if s.recv {
		fmt.Fprintf(b, "\treturn MethodDef[T]{d}\n}\n\n")
	} else {
		fmt.Fprintf(b, "\treturn FuncDef{d}\n}\n\n")
	}
}

// writeArgs decodes the n arguments a1..an, returning failRet on error.
func writeArgs(b *bytes.Buffer, n int, failRet string) {
	for i := 1; i <= n; i++ {
		fmt.Fprintf(b, "\t\ta%d, err := arg[A%d](&cx, %d)\n\t\tif err != nil {\n\t\t\treturn %s\n\t\t}\n", i, i, i-1, failRet)
	}
}

// argList returns "first, a1, ..., an" (without first if empty).
func argList(n int, first string) string {
	var as []string
	if first != "" {
		as = append(as, first)
	}
	for i := 1; i <= n; i++ {
		as = append(as, fmt.Sprintf("a%d", i))
	}
	return strings.Join(as, ", ")
}
