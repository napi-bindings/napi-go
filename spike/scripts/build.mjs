// Builds the spike addons (prototype of the future `napi-go build`).
//   node scripts/build.mjs            → build/basic.node, build/second.node, build/cref.node
// Environment variables: CC (C compiler for cgo, e.g. "zig cc"), GO (defaults to "go").
import { spawnSync } from 'node:child_process'
import { mkdirSync, rmSync, existsSync, statSync } from 'node:fs'
import { join, dirname } from 'node:path'
import { fileURLToPath } from 'node:url'

const root = join(dirname(fileURLToPath(import.meta.url)), '..')
const out = join(root, 'build')
mkdirSync(out, { recursive: true })

function run(cmd, args, env = {}) {
  const t0 = Date.now()
  const r = spawnSync(cmd, args, { cwd: root, stdio: 'inherit', env: { ...process.env, ...env } })
  if (r.error) { // executable not found or spawn failed
    console.error(`✗ failed to execute ${cmd}: ${r.error.message}`)
    process.exit(1)
  }
  if (r.status !== 0) {
    console.error(`✗ ${cmd} ${args.join(' ')} (exit ${r.status})`)
    process.exit(r.status ?? 1)
  }
  return Date.now() - t0
}

const go = process.env.GO || 'go'
for (const name of ['basic', 'second']) {
  const target = join(out, `${name}.node`)
  // -buildvcs=false: VCS info is unnecessary in a .node addon and the build should not depend on git
  // (in CI containers the repository is owned by another user → "dubious ownership", exit 128).
  const ms = run(go, ['build', '-buildmode=c-shared', '-buildvcs=false', '-trimpath', '-ldflags=-s -w', '-o', target, `./addons/${name}`], { CGO_ENABLED: '1' })
  rmSync(join(out, `${name}.h`), { force: true }) // header generated by c-shared: unneeded for a .node addon
  console.log(`✓ ${name}.node  ${(statSync(target).size / 1048576).toFixed(2)} MB  (${ms} ms)`)
}

// Pure C baseline (Unix only: on Windows node.lib would be required).
if (process.platform !== 'win32') {
  const cc = process.env.CREF_CC || 'cc'
  const extra = process.platform === 'darwin' ? ['-undefined', 'dynamic_lookup'] : []
  run(cc, ['-O2', '-shared', '-fPIC', '-Inapi/include', 'addons/cref/cref.c', '-o', join(out, 'cref.node'), ...extra])
  console.log('✓ cref.node (C baseline)')
} else if (existsSync(join(out, 'cref.node'))) {
  rmSync(join(out, 'cref.node'))
}
